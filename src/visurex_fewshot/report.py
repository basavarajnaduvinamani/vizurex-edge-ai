"""Summaries, markdown table and plot generated only from saved run records.

Nothing here contains or estimates a number: every value comes from the
``runs`` list written by ``scripts/run_fewshot.py``.
"""
from __future__ import annotations

from collections import defaultdict
from typing import Dict, List

import numpy as np

METRICS = ("image_auroc", "defect_recall", "false_alarm_rate", "pixel_aupro")
# Fixed categorical order (method identity never depends on rank).
METHOD_COLOURS = {"patchcore_wrn50": "#2a78d6", "dinov2_vits14": "#eb6834",
                  "dinov2_vits14_masked": "#1baf7a", "tiny_random": "#6250d6"}
FALLBACK_COLOURS = ["#eda100", "#e87ba4", "#008300", "#e34948"]


def shot_key(k):
    return float("inf") if k == "full" else float(k)


def summarize(runs: List[dict]) -> List[dict]:
    groups: Dict[tuple, List[dict]] = defaultdict(list)
    for run in runs:
        groups[(run["category"], run["method"], run["k"])].append(run)
    rows = []
    for (category, method, k), members in sorted(
            groups.items(), key=lambda item: (item[0][0], item[0][1], shot_key(item[0][2]))):
        row = {"category": category, "method": method, "k": k,
               "seeds": sorted(m["seed"] for m in members)}
        for metric in METRICS:
            values = [m[metric] for m in members if m.get(metric) is not None]
            row[metric + "_mean"] = float(np.mean(values)) if values else None
            row[metric + "_std"] = float(np.std(values)) if len(values) > 1 else None
        row["nn_ms_per_image_median"] = float(np.median([m["nn_ms_per_image_median"] for m in members]))
        rows.append(row)
    return rows


def _cell(mean, std, percent=False):
    if mean is None:
        return "n/a"
    scale, digits = (100.0, 1) if percent else (1.0, 4)
    text = f"{mean * scale:.{digits}f}"
    if std is not None:
        text += f" ± {std * scale:.{digits}f}"
    return text + ("%" if percent else "")


def markdown_table(summary: List[dict], timings: List[dict], source: str) -> str:
    lines = [
        "# Few-shot results (generated)",
        "",
        f"Generated by `scripts/run_fewshot.py` from `{source}`. Do not edit by hand.",
        "Mean ± standard deviation over the listed seeds. `full` uses every reference-pool image.",
        "Threshold: 99th percentile of normal validation scores, fixed before test scoring.",
        "",
        "| Category | Method | k | Seeds | Image AUROC | Defect recall | False-alarm rate | Pixel AUPRO | Scoring ms/img (NN + map) |",
        "|---|---|---:|---|---:|---:|---:|---:|---:|",
    ]
    for row in summary:
        lines.append("| {category} | {method} | {k} | {seeds} | {auroc} | {recall} | {far} | {aupro} | {nn:.1f} |".format(
            category=row["category"], method=row["method"], k=row["k"],
            seeds=",".join(str(s) for s in row["seeds"]),
            auroc=_cell(row["image_auroc_mean"], row["image_auroc_std"]),
            recall=_cell(row["defect_recall_mean"], row["defect_recall_std"], percent=True),
            far=_cell(row["false_alarm_rate_mean"], row["false_alarm_rate_std"], percent=True),
            aupro=_cell(row["pixel_aupro_mean"], row["pixel_aupro_std"]),
            nn=row["nn_ms_per_image_median"]))
    if timings:
        lines += ["", "## CPU timing per category and backbone", "",
                  "Feature extraction is measured once per image (batch 1); k-shot runs reuse cached features.", "",
                  "| Category | Method | Backbone | Images embedded | Embed median / p95 ms | Total embed s | Threads |",
                  "|---|---|---|---:|---|---:|---:|"]
        for t in timings:
            lines.append(f"| {t['category']} | {t['method']} | `{t['backbone']}` | {t['images_embedded']} | "
                         f"{t['embed_ms_median']:.1f} / {t['embed_ms_p95']:.1f} | {t['embed_seconds_total']:.1f} | {t['torch_threads']} |")
    return "\n".join(lines) + "\n"


def plot(summary: List[dict], path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    categories = sorted({row["category"] for row in summary})
    methods = sorted({row["method"] for row in summary})
    colours = dict(METHOD_COLOURS)
    for index, method in enumerate(m for m in methods if m not in colours):
        colours[method] = FALLBACK_COLOURS[index % len(FALLBACK_COLOURS)]
    shots = sorted({row["k"] for row in summary}, key=shot_key)
    positions = {k: i for i, k in enumerate(shots)}
    columns = min(3, len(categories))
    rows_n = int(np.ceil(len(categories) / columns))
    figure, axes = plt.subplots(rows_n, columns, figsize=(4.2 * columns, 3.4 * rows_n),
                                squeeze=False, sharey=True)
    for axis in axes.ravel()[len(categories):]:
        axis.set_visible(False)
    for axis, category in zip(axes.ravel(), categories):
        for method in methods:
            points = [r for r in summary if r["category"] == category and r["method"] == method
                      and r["image_auroc_mean"] is not None]
            if not points:
                continue
            x = [positions[r["k"]] for r in points]
            y = [r["image_auroc_mean"] for r in points]
            err = [r["image_auroc_std"] or 0.0 for r in points]
            axis.errorbar(x, y, yerr=err, color=colours[method], linewidth=2, marker="o",
                          markersize=5, capsize=3, label=method)
        axis.set_title(category, fontsize=10, color="#0b0b0b")
        axis.set_xticks(range(len(shots)), [str(k) for k in shots])
        axis.set_xlabel("reference images (k)", fontsize=9, color="#52514e")
        axis.grid(axis="y", color="#e6e5e1", linewidth=0.8)
        for side in ("top", "right"):
            axis.spines[side].set_visible(False)
    axes[0][0].set_ylabel("image AUROC (mean ± sd over seeds)", fontsize=9, color="#52514e")
    handles, labels = axes.ravel()[0].get_legend_handles_labels()
    if handles:
        figure.legend(handles, labels, loc="upper center", ncol=len(labels), frameon=False, fontsize=9)
    figure.tight_layout(rect=(0, 0, 1, 0.92))
    figure.savefig(path, dpi=150, facecolor="#fcfcfb")
    plt.close(figure)
